SELECT
    u.uid                       AS patient_id,
    u.uname                     AS users_uname,
    u.UserType                  AS users_UserType,
    u.upwd                      AS users_upwd,
    u.umobileno                 AS users_umobileno,
    u.upagerno                  AS users_upagerno,
    u.ufname                    AS users_ufname,
    u.uminitial                 AS users_uminitial,
    u.ulname                    AS users_ulname,
    u.uemail                    AS users_uemail,
    u.upaddress                 AS users_upaddress,
    u.upcity                    AS users_upcity,
    u.upPhone                   AS users_upPhone,
    u.dob                       AS users_dob,
    u.ssn                       AS users_ssn,
    u.upaddress2                AS users_upaddress2,
    u.initials                  AS users_initials,
    u.ptDob                     AS users_ptDob,
    u.upreviousname             AS users_upreviousname,
    p.employername              AS patients_employername,
    p.employeraddress           AS patients_employeraddress,
    p.employeraddress2          AS patients_employeraddress2,
    p.employercity              AS patients_employercity,
    p.employerPhone             AS patients_employerPhone,
    p.insname                   AS patients_insname,
    p.insgroupno                AS patients_insgroupno,
    p.inssubscriberno           AS patients_inssubscriberno,
    p.inscopay                  AS patients_inscopay,
    p.insname2                  AS patients_insname2,
    p.insgroupno2               AS patients_insgroupno2,
    p.inssubscriberno2          AS patients_inssubscriberno2,
    p.inscopay2                 AS patients_inscopay2,
    p.straddress                AS patients_straddress,
    p.city                      AS patients_city,
    p.insId                     AS patients_insId,
    p.insId2                    AS patients_insId2,
    p.strAddress2               AS patients_strAddress2,
    p.GrId                      AS patients_GrId,
    p.preferred_name            AS patients_preferred_name
FROM users u
LEFT JOIN patients p ON u.uid = p.pid
WHERE u.uid <> 0;